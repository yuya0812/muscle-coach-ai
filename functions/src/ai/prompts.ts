export function buildUserProfileContext(profile: {
  name: string;
  goal: string;
  level: string;
  equipment: string;
  frequency: number;
}): string {
  const goalMap: Record<string, string> = {
    muscle_gain: "筋肥大",
    strength: "筋力向上",
    diet: "ダイエット",
    health: "健康維持",
  };

  const levelMap: Record<string, string> = {
    beginner: "初心者",
    intermediate: "中級者",
    advanced: "上級者",
  };

  return [
    `名前: ${profile.name}`,
    `目標: ${goalMap[profile.goal] || profile.goal || "未設定"}`,
    `レベル: ${levelMap[profile.level] || profile.level || "未設定"}`,
    `利用可能器具: ${profile.equipment || "未設定"}`,
    `週のトレーニング頻度: ${profile.frequency}回`,
  ].join("\n");
}
